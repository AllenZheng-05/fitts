// pnpm demo:mirror [--push] — exports demo/chat, demo/hartwell, demo/basil-ember and
// demo/basil-ember-android as standalone repos for AllenZheng-05/fitts-demo-chat, -hartwell,
// -basil-ember and -basil-ember-android (SPEC-phase2 §3).
//
// A plain `git subtree split` isn't enough: the demos depend on @fitts/vite-plugin through the
// workspace and extend the monorepo's tsconfig. Each export vendors the plugin under
// fitts-plugin/ (a `file:` dependency) and inlines the tsconfig, then commits to
// .fitts-dev/mirror/<name>. Without --push nothing leaves this machine.
//
// A demo already on GitHub is fetched first and its export is committed on top of the remote's
// main, so a push is always a fast-forward and the remote's history (Allen's own first commit of
// the untouched website, Nov 2) is never rewritten. Never a force-push.
import { execFileSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const push = process.argv.includes('--push');
const OWNER = process.env.FITTS_MIRROR_OWNER ?? 'AllenZheng-05';
const DEMOS = [
  { dir: 'demo/chat', repo: 'fitts-demo-chat' },
  { dir: 'demo/hartwell', repo: 'fitts-demo-hartwell' },
  // Generated by Muse Code from one prompt (prompt.md), untouched: its problems are its own.
  // Allen created the GitHub repos with these names (GitHub ignores case).
  { dir: 'demo/basil-ember', repo: 'fitts-demo-basil-ember', remote: 'Fitts-demo-basil-ember' },
  // Basil & Ember's ordering app (Expo); its issues are planted (PLANTED.md).
  {
    dir: 'demo/basil-ember-android',
    repo: 'fitts-demo-basil-ember-android',
    remote: 'Fitts-demo-basil-ember-android',
  },
];

/** Paths an export never writes (dependencies, build output, local build caches). */
const unmanaged = (p) =>
  /(^|[\\/])(node_modules|dist|\.vite)([\\/]|$)/.test(p) || p.endsWith('.tsbuildinfo');

const git = (cwd, ...args) => execFileSync('git', args, { cwd, encoding: 'utf8' }).trim();
const base = JSON.parse(readFileSync(join(ROOT, 'tsconfig.base.json'), 'utf8')).compilerOptions;

for (const { dir, repo, remote } of DEMOS) {
  const src = join(ROOT, dir);
  const out = join(ROOT, '.fitts-dev', 'mirror', repo);
  const url = `https://github.com/${OWNER}/${remote ?? repo}.git`;
  const fresh = !existsSync(join(out, '.git'));
  if (fresh) {
    mkdirSync(out, { recursive: true });
    git(out, 'init', '-q', '-b', 'main');
  }
  const remotes = git(out, 'remote').split('\n');
  if (remotes.includes('origin')) git(out, 'remote', 'set-url', 'origin', url);
  else git(out, 'remote', 'add', 'origin', url);
  // Build on what's published: the remote's main, when there is one. The export below replaces
  // the whole tree, so nothing a local-only commit held is lost.
  let upstream = false;
  try {
    // A repo that isn't there mustn't open a sign-in prompt.
    execFileSync('git', ['fetch', '-q', 'origin', 'main'], {
      cwd: out,
      stdio: 'ignore',
      env: { ...process.env, GIT_TERMINAL_PROMPT: '0', GCM_INTERACTIVE: 'never' },
    });
    upstream = true;
  } catch {
    // Not published yet (or offline): the local history stands.
  }
  if (upstream) git(out, 'reset', '-q', '--hard', 'origin/main');
  // Replace the tree (keeping .git) with the current demo. Unmanaged files already in the repo
  // (the website's committed tsconfig.tsbuildinfo) stay as they are.
  for (const entry of execFileSync('git', ['ls-files'], { cwd: out, encoding: 'utf8' })
    .split('\n')
    .filter((e) => e && !unmanaged(e))) {
    rmSync(join(out, entry), { force: true });
  }
  cpSync(src, out, { recursive: true, filter: (p) => !unmanaged(p) });
  // A demo on the workspace plugin gets it vendored; one with the one-file plugin has it already.
  const usesWorkspacePlugin = Boolean(
    JSON.parse(readFileSync(join(out, 'package.json'), 'utf8')).devDependencies?.[
      '@fitts/vite-plugin'
    ],
  );
  if (usesWorkspacePlugin) {
    mkdirSync(join(out, 'fitts-plugin'), { recursive: true });
    cpSync(join(ROOT, 'packages/vite-plugin/src'), join(out, 'fitts-plugin/src'), {
      recursive: true,
    });
    const pluginPkg = JSON.parse(
      readFileSync(join(ROOT, 'packages/vite-plugin/package.json'), 'utf8'),
    );
    delete pluginPkg.devDependencies;
    delete pluginPkg.scripts;
    writeFileSync(
      join(out, 'fitts-plugin/package.json'),
      JSON.stringify(pluginPkg, null, 2) + '\n',
    );

    const pkg = JSON.parse(readFileSync(join(out, 'package.json'), 'utf8'));
    pkg.devDependencies['@fitts/vite-plugin'] = 'file:./fitts-plugin';
    writeFileSync(join(out, 'package.json'), JSON.stringify(pkg, null, 2) + '\n');
  }
  // Only a demo that extends the monorepo's tsconfig gets it inlined; a standalone one is kept.
  const ts = JSON.parse(readFileSync(join(out, 'tsconfig.json'), 'utf8'));
  if (ts.extends) {
    delete ts.extends;
    ts.compilerOptions = { ...base, ...ts.compilerOptions };
    writeFileSync(join(out, 'tsconfig.json'), JSON.stringify(ts, null, 2) + '\n');
  }
  // The demo's own .gitignore stays; Fitts's worktrees are added to it.
  const ignore = existsSync(join(out, '.gitignore'))
    ? readFileSync(join(out, '.gitignore'), 'utf8')
    : '';
  const need = ['node_modules/', 'dist/', '.fitts-worktrees/'].filter(
    (l) => !ignore.split(/\r?\n/).some((x) => x.replace(/\/$/, '') === l.replace(/\/$/, '')),
  );
  if (need.length)
    writeFileSync(join(out, '.gitignore'), ignore.replace(/\n?$/, '\n') + need.join('\n') + '\n');
  // A committed lockfile, so clones (and Fitts's fix worktrees) install the same versions. A
  // demo with its own npm lockfile (the Expo app) keeps it.
  if (!existsSync(join(out, 'package-lock.json')))
    execFileSync('pnpm', ['install', '--lockfile-only', '--offline', '--ignore-workspace'], {
      cwd: out,
      stdio: 'ignore',
      shell: process.platform === 'win32',
    });

  git(out, 'add', '-A');
  const dirty = git(out, 'status', '--porcelain');
  if (dirty) {
    const sha = git(ROOT, 'rev-parse', '--short', 'HEAD');
    git(out, '-c', 'user.name=Allen Zheng', 'commit', '-qm', `Sync from fitts@${sha}`);
  }
  console.log(`${repo}: ${dirty ? 'committed' : 'up to date'} at ${out}`);

  if (push) {
    // A fast-forward of the remote's main, or git refuses: never forced.
    execFileSync('git', ['push', '-u', 'origin', 'main'], { cwd: out, stdio: 'inherit' });
  } else if (!upstream) {
    console.log(
      `  to publish: gh repo create ${OWNER}/${remote ?? repo} --public && pnpm demo:mirror --push`,
    );
  } else if (dirty) {
    console.log(`  to publish: pnpm demo:mirror --push (a fast-forward of ${url})`);
  }
}
